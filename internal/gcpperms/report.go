package gcpperms

import (
	"encoding/json"
	"fmt"
	"io"
	"path"
	"regexp"
	"slices"
	"sort"
	"strings"

	"github.com/cockroachdb/errors"
)

// versionRE matches a version element of an import path, such as v2 or
// apiv1beta1.
var versionRE = regexp.MustCompile(`^(api)?v\d+((alpha|beta|a|b)\d*)?$`)

// errWriter remembers the first write error, so a report can be written
// with one check at the end.
type errWriter struct {
	w   io.Writer
	err error
}

// WriteText writes a human-readable report. With verbose, each SDK call is
// followed by the first-party call sites that reach it.
func WriteText(w io.Writer, bins []Binary, verbose bool) error {
	ew := &errWriter{w: w}
	for i, b := range bins {
		if i > 0 {
			ew.printf("\n")
		}
		writeBinaryText(ew, b, verbose)
	}
	return ew.err
}

// WriteJSON writes the result as indented JSON.
func WriteJSON(w io.Writer, r Result) error {
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	return errors.Wrap(enc.Encode(r), "gcpperms.WriteJSON")
}

// WriteRoles writes one IAM custom role definition per binary, in the YAML
// format accepted by `gcloud iam roles create --file`. Conditional
// permissions are included so the role works on every path; review them.
func WriteRoles(w io.Writer, bins []Binary) error {
	ew := &errWriter{w: w}
	var n int
	for _, b := range bins {
		perms := b.Permissions()
		cond := b.ConditionalPermissions()
		if len(perms)+len(cond) == 0 {
			continue
		}
		if n > 0 {
			ew.printf("---\n")
		}
		n++
		ew.printf("# Generated by gcpperms for %s\n", b.Package)
		ew.printf("title: %s\n", path.Base(b.Package))
		ew.printf("description: Permissions reachable from %s\n", b.Package)
		ew.printf("stage: GA\n")
		ew.printf("includedPermissions:\n")
		all := append(append([]string(nil), perms...), cond...)
		sort.Strings(all)
		isCond := make(map[string]bool)
		for _, p := range cond {
			isCond[p] = true
		}
		for _, p := range all {
			if isCond[p] {
				ew.printf("- %s # conditional\n", p)
			} else {
				ew.printf("- %s\n", p)
			}
		}
	}
	return ew.err
}

// WritePredefinedRoles writes, for each binary, the predefined roles that
// grant its permissions with the least excess, from b.PredefinedRoles.
func WritePredefinedRoles(w io.Writer, bins []Binary) error {
	ew := &errWriter{w: w}
	for i, b := range bins {
		if i > 0 {
			ew.printf("\n")
		}
		ew.printf("== %s\n", b.Package)
		writeSelection(ew, b.PredefinedRoles)
	}
	return ew.err
}

// writeBinaryText writes one binary's section of the text report.
func writeBinaryText(ew *errWriter, b Binary, verbose bool) {
	ew.printf("== %s\n", b.Package)
	if len(b.Calls) == 0 {
		ew.printf("  no Google Cloud API calls\n")
		return
	}
	// Invert calls into permission -> APIs that need it.
	need := make(map[string][]string)
	maybe := make(map[string][]string)
	for _, c := range b.Calls {
		for _, p := range c.Permissions {
			need[p] = append(need[p], shortAPI(c.API))
		}
		for _, p := range c.Conditional {
			maybe[p] = append(maybe[p], shortAPI(c.API))
		}
	}
	writePermissions(ew, "Permissions", b.Permissions(), need)
	writePermissions(ew, "Conditional permissions", b.ConditionalPermissions(), maybe)
	if svcs := b.Services(); len(svcs) > 0 {
		ew.printf("  APIs: %s\n", strings.Join(svcs, ", "))
	}
	writeNotes(ew, b.Calls)
	if un := b.Unmapped(); len(un) > 0 {
		ew.printf("  Unmapped SDK calls (add rules to table.go):\n")
		writeSites(ew, un)
	}
	if verbose {
		ew.printf("  Call sites:\n")
		writeSites(ew, slices.DeleteFunc(slices.Clone(b.Calls), func(c Call) bool {
			return !c.Mapped
		}))
	}
}

// writePermissions writes a titled list of perms, each with the APIs that
// need it, or nothing when perms is empty.
func writePermissions(ew *errWriter, title string, perms []string, apis map[string][]string) {
	if len(perms) == 0 {
		return
	}
	ew.printf("  %s:\n", title)
	for _, p := range perms {
		ew.printf("    %-45s %s\n", p, strings.Join(apis[p], ", "))
	}
}

// writeNotes writes the notes of calls that have one.
func writeNotes(ew *errWriter, calls []Call) {
	var notes []Call
	for _, c := range calls {
		if c.Note != "" {
			notes = append(notes, c)
		}
	}
	if len(notes) == 0 {
		return
	}
	ew.printf("  Notes:\n")
	for _, c := range notes {
		ew.printf("    %s: %s\n", shortAPI(c.API), c.Note)
	}
}

// writeSites writes each call's API followed by its call sites.
func writeSites(ew *errWriter, calls []Call) {
	for _, c := range calls {
		ew.printf("    %s\n", c.API)
		for _, s := range c.Sites {
			ew.printf("      %s:%d\n", s.File, s.Line)
		}
	}
}

// writeSelection writes one binary's predefined roles.
func writeSelection(ew *errWriter, sel *RoleSelection) {
	if sel == nil || len(sel.Grants)+len(sel.Uncovered) == 0 {
		ew.printf("  no permissions required\n")
		return
	}
	if len(sel.Grants) > 0 {
		ew.printf(
			"  Predefined roles (%d permissions beyond those required):\n",
			sel.Excess,
		)
		for _, g := range sel.Grants {
			ew.printf("    %-45s %s, %d permissions\n", g.Role, g.Title, g.Size)
			ew.printf("      for %s\n", strings.Join(g.Covers, ", "))
		}
	}
	if len(sel.Uncovered) > 0 {
		ew.printf("  Granted by no allowed predefined role (use a custom role):\n")
		for _, p := range sel.Uncovered {
			ew.printf("    %s\n", p)
		}
	}
	if sel.Inexact {
		ew.printf("  Some roles were chosen greedily; a smaller set may exist.\n")
	}
}

// shortAPI trims the import path to its last unversioned element:
// "cloud.google.com/go/datastore.Client.Get" -> "datastore.Client.Get",
// "cloud.google.com/go/pubsub/v2/apiv1.X" -> "pubsub/v2/apiv1.X".
func shortAPI(api string) string {
	pkg, name := splitAPI(api)
	elems := strings.Split(pkg, "/")
	i := len(elems) - 1
	for i > 0 && versionRE.MatchString(elems[i]) {
		i--
	}
	return strings.Join(elems[i:], "/") + "." + name
}

func (e *errWriter) printf(format string, args ...any) {
	if e.err != nil {
		return
	}
	_, e.err = fmt.Fprintf(e.w, format, args...)
}
