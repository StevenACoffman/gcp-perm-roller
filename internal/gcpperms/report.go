package gcpperms

import (
	"encoding/json"
	"fmt"
	"io"
	"path"
	"regexp"
	"slices"
	"sort"
	"strings"

	"github.com/cockroachdb/errors"
)

// versionRE matches a version element of an import path, such as v2 or
// apiv1beta1.
var versionRE = regexp.MustCompile(`^(api)?v\d+((alpha|beta|a|b)\d*)?$`)

// errWriter remembers the first write error, so a report can be written
// with one check at the end.
type errWriter struct {
	w   io.Writer
	err error
}

// WriteText writes a human-readable report. With verbose, each SDK call is
// followed by the first-party call sites that reach it.
func WriteText(w io.Writer, bins []Binary, verbose bool) error {
	ew := &errWriter{w: w}
	for i, b := range bins {
		if i > 0 {
			ew.printf("\n")
		}
		writeBinaryText(ew, b, verbose)
	}
	return ew.err
}

// WriteJSON writes v, such as a Result or a MemberAccess, as indented
// JSON.
func WriteJSON(w io.Writer, v any) error {
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	// Condition expressions compare with < and >, which HTML escaping
	// would make unreadable.
	enc.SetEscapeHTML(false)
	return errors.Wrap(enc.Encode(v), "gcpperms.WriteJSON")
}

// WriteRoles writes one IAM custom role definition per binary, in the YAML
// format accepted by `gcloud iam roles create --file`. Conditional
// permissions are included so the role works on every path; review them.
// Permissions custom roles do not support are commented out, and those
// Google is testing in custom roles are marked.
func WriteRoles(w io.Writer, bins []Binary) error {
	ew := &errWriter{w: w}
	var n int
	for _, b := range bins {
		perms := b.Permissions()
		cond := b.ConditionalPermissions()
		if len(perms)+len(cond) == 0 {
			continue
		}
		if n > 0 {
			ew.printf("---\n")
		}
		n++
		ew.printf("# Generated by gcpperms for %s\n", b.Package)
		ew.printf("title: %s\n", path.Base(b.Package))
		ew.printf("description: Permissions reachable from %s\n", b.Package)
		ew.printf("stage: GA\n")
		ew.printf("includedPermissions:\n")
		all := append(append([]string(nil), perms...), cond...)
		sort.Strings(all)
		isCond := make(map[string]bool)
		for _, p := range cond {
			isCond[p] = true
		}
		for _, p := range all {
			ew.printf("%s\n", roleItem(p, isCond[p]))
		}
	}
	return ew.err
}

// WritePredefinedRoles writes, for each binary, the predefined roles that
// grant its permissions with the least excess, from b.PredefinedRoles.
func WritePredefinedRoles(w io.Writer, bins []Binary) error {
	ew := &errWriter{w: w}
	for i, b := range bins {
		if i > 0 {
			ew.printf("\n")
		}
		ew.printf("== %s\n", b.Package)
		writeSelection(ew, b.PredefinedRoles)
	}
	return ew.err
}

// WriteMemberAccess writes the roles a member holds, how many permissions
// they grant, and the predefined roles that grant those, from
// a.PredefinedRoles.
func WriteMemberAccess(w io.Writer, a *MemberAccess) error {
	ew := &errWriter{w: w}
	ew.printf("== %s\n", a.Member)
	ew.printf("  Holds:\n")
	for i := range a.Bindings {
		b := &a.Bindings[i]
		if note := bindingNote(b); note != "" {
			ew.printf("    %-45s %s\n", b.Role, note)
		} else {
			ew.printf("    %s\n", b.Role)
		}
	}
	ew.printf("  %d permissions", len(a.Permissions))
	if n := len(a.ConditionalPermissions); n > 0 {
		ew.printf(", and %d more under conditions", n)
	}
	ew.printf("\n")
	writeDenials(ew, a)
	writeSelection(ew, a.PredefinedRoles)
	return ew.err
}

// writeBinaryText writes one binary's section of the text report.
func writeBinaryText(ew *errWriter, b Binary, verbose bool) {
	ew.printf("== %s\n", b.Package)
	if len(b.Calls) == 0 {
		ew.printf("  no Google Cloud API calls\n")
		return
	}
	// Invert calls into permission -> APIs that need it.
	need := make(map[string][]string)
	maybe := make(map[string][]string)
	for _, c := range b.Calls {
		for _, p := range c.Permissions {
			need[p] = append(need[p], shortAPI(c.API))
		}
		for _, p := range c.Conditional {
			maybe[p] = append(maybe[p], shortAPI(c.API))
		}
	}
	writePermissions(ew, "Permissions", b.Permissions(), need)
	writePermissions(ew, "Conditional permissions", b.ConditionalPermissions(), maybe)
	if svcs := b.Services(); len(svcs) > 0 {
		ew.printf("  APIs: %s\n", strings.Join(svcs, ", "))
	}
	writeNotes(ew, b.Calls)
	if un := b.Unmapped(); len(un) > 0 {
		ew.printf("  Unmapped SDK calls (add rules to table.go):\n")
		writeSites(ew, un)
	}
	if verbose {
		ew.printf("  Call sites:\n")
		writeSites(ew, slices.DeleteFunc(slices.Clone(b.Calls), func(c Call) bool {
			return !c.Mapped
		}))
	}
}

// writePermissions writes a titled list of perms, each with the APIs that
// need it, or nothing when perms is empty.
func writePermissions(ew *errWriter, title string, perms []string, apis map[string][]string) {
	if len(perms) == 0 {
		return
	}
	ew.printf("  %s:\n", title)
	for _, p := range perms {
		ew.printf("    %-45s %s\n", p, strings.Join(apis[p], ", "))
	}
}

// writeNotes writes the notes of calls that have one.
func writeNotes(ew *errWriter, calls []Call) {
	var notes []Call
	for _, c := range calls {
		if c.Note != "" {
			notes = append(notes, c)
		}
	}
	if len(notes) == 0 {
		return
	}
	ew.printf("  Notes:\n")
	for _, c := range notes {
		ew.printf("    %s: %s\n", shortAPI(c.API), c.Note)
	}
}

// writeSites writes each call's API followed by its call sites.
func writeSites(ew *errWriter, calls []Call) {
	for _, c := range calls {
		ew.printf("    %s\n", c.API)
		for _, s := range c.Sites {
			ew.printf("      %s:%d\n", s.File, s.Line)
		}
	}
}

// writeDenials writes how a's deny policies deny its permissions: those
// they deny, which are not counted, and those they may deny, which are.
func writeDenials(ew *errWriter, a *MemberAccess) {
	if a.DenyPolicies == 0 {
		return
	}
	ew.printf("  %d deny policies\n", a.DenyPolicies)
	var certain, possible []Denial
	for _, d := range a.Denials {
		if d.Certain {
			certain = append(certain, d)
		} else {
			possible = append(possible, d)
		}
	}
	writeDenialList(ew, "Denied, so not counted:", certain)
	writeDenialList(ew, "Possibly denied, still counted:", possible)
}

// writeDenialList writes denials under title, if there are any.
func writeDenialList(ew *errWriter, title string, denials []Denial) {
	if len(denials) == 0 {
		return
	}
	ew.printf("  %s\n", title)
	for _, d := range denials {
		note := "by " + d.Policy
		if d.Reason != "" {
			note += ", " + d.Reason
		}
		ew.printf("    %-45s %s\n", d.Permission, note)
	}
}

// writeSelection writes one binary's predefined roles.
func writeSelection(ew *errWriter, sel *RoleSelection) {
	if sel == nil || len(sel.Grants)+len(sel.Uncovered) == 0 {
		ew.printf("  no permissions required\n")
		return
	}
	if len(sel.Grants) > 0 {
		ew.printf(
			"  Predefined roles (%d permissions beyond those required):\n",
			sel.Excess,
		)
		for _, g := range sel.Grants {
			ew.printf("    %-45s %s, %d permissions\n", g.Role, g.Title, g.Size)
			ew.printf("      for %s\n", strings.Join(g.Covers, ", "))
		}
	}
	if len(sel.Uncovered) > 0 {
		ew.printf("  Granted by no allowed predefined role (use a custom role):\n")
		for _, p := range sel.Uncovered {
			if level, ok := sel.CustomRoleSupport[p]; ok {
				ew.printf("    %-45s %s\n", p, supportNote(level))
			} else {
				ew.printf("    %s\n", p)
			}
		}
	}
	if sel.Inexact {
		ew.printf("  Some roles were chosen greedily; a smaller set may exist.\n")
	}
}

// roleItem is perm's line in a role's includedPermissions, with notes on
// whether it is conditional and how custom roles support it. gcloud
// rejects a role holding an unsupported permission, so that line is
// commented out, but kept in sight.
func roleItem(perm string, conditional bool) string {
	var notes []string
	if conditional {
		notes = append(notes, "conditional")
	}
	level := CustomRoleSupport(perm)
	if level != Supported {
		notes = append(notes, supportNote(level))
	}
	item := "- " + perm
	if level == NotSupported {
		item = "# " + item
	}
	if len(notes) > 0 {
		item += " # " + strings.Join(notes, "; ")
	}
	return item
}

// supportNote says what level means for a permission in a custom role.
func supportNote(level SupportLevel) string {
	if level == NotSupported {
		return "not supported in custom roles"
	}
	return "testing in custom roles"
}

// bindingNote says when a held binding applies, naming its condition, the
// groups it is held through, and where it is inherited from.
func bindingNote(b *HeldBinding) string {
	var notes []string
	if b.Condition != nil {
		notes = append(notes, conditionNote(b.State)+": "+b.Condition.Name())
	}
	if len(b.Through) > 0 {
		notes = append(notes, "through "+strings.Join(b.Through, ", "))
	}
	if b.Resource != "" {
		notes = append(notes, "inherited from "+b.Resource)
	}
	return strings.Join(notes, "; ")
}

// conditionNote names the state of a binding that has a condition.
func conditionNote(state ConditionState) string {
	switch state {
	case Unconditional:
		return "temporary"
	case Expired:
		return "expired"
	case Conditional:
		return "conditional"
	}
	return string(state)
}

// shortAPI trims the import path to its last unversioned element:
// "cloud.google.com/go/datastore.Client.Get" -> "datastore.Client.Get",
// "cloud.google.com/go/pubsub/v2/apiv1.X" -> "pubsub/v2/apiv1.X".
func shortAPI(api string) string {
	pkg, name := splitAPI(api)
	elems := strings.Split(pkg, "/")
	i := len(elems) - 1
	for i > 0 && versionRE.MatchString(elems[i]) {
		i--
	}
	return strings.Join(elems[i:], "/") + "." + name
}

func (e *errWriter) printf(format string, args ...any) {
	if e.err != nil {
		return
	}
	_, e.err = fmt.Fprintf(e.w, format, args...)
}
