// row is one table row as the page writes it.
func row(perm, level string) string {
	return fmt.Sprintf(
		"<tr>\n      <td class=\"column1-class\"><code translate=\"no\" dir=\"ltr\">%s</code></td>\n"+
			"      <td class=\"column2-class\"><code translate=\"no\" dir=\"ltr\">%s</code></td>\n    </tr>\n",
		perm,
		level,
	)
}

// page is a support-levels page listing extra after enough SUPPORTED
// permissions to pass the size check.
func page(extra ...string) string {
	var b strings.Builder
	// The legend's rows have no column classes, so they are not permissions.
	b.WriteString(
		"<tr><td><code>NOT_SUPPORTED</code></td><td>The permission is not supported.</td></tr>\n",
	)
	for i := range minRows {
		b.WriteString(row(fmt.Sprintf("svc.things.verb%d", i), "SUPPORTED"))
	}
	for _, r := range extra {
		b.WriteString(r)
	}
	return b.String()
}

func TestGenerate(t *testing.T) {
	tests := map[string]struct {
		status  int
		body    string
		want    []string // lines the source must contain
		wantErr string
	}{
		"exceptions only, sorted": {
			status: http.StatusOK,
			body: page(
				row("b.things.list", "TESTING"),
				row("a.things.get", "NOT_SUPPORTED"),
				row("b.things.list", "TESTING"),
			),
			want: []string{
				"// Code generated by gensupport from " + pageURL + "; DO NOT EDIT.",
				"\t\"a.things.get\":  NotSupported,\n\t\"b.things.list\": Testing,\n}",
			},
		},
		"too few rows": {
			status:  http.StatusOK,
			body:    row("a.things.get", "NOT_SUPPORTED"),
			wantErr: "found 1 permissions, expected at least 10000",
		},
		"unknown level": {
			status:  http.StatusOK,
			body:    page(row("a.things.get", "MAYBE")),
			wantErr: `a.things.get: unknown support level "MAYBE"`,
		},
		"conflicting levels": {
			status:  http.StatusOK,
			body:    page(row("a.things.get", "TESTING"), row("a.things.get", "NOT_SUPPORTED")),
			wantErr: "a.things.get is listed as both TESTING and NOT_SUPPORTED",
		},
		"server error": {
			status:  http.StatusInternalServerError,
			wantErr: "500 Internal Server Error",
		},
	}
	for name, tc := range tests {
		t.Run(name, func(t *testing.T) {
			srv := httptest.NewServer(
				http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
					w.WriteHeader(tc.status)
					fmt.Fprint(w, tc.body)
				}),
			)
			t.Cleanup(srv.Close)

			src, err := generate(context.Background(), srv.Client(), srv.URL)
			if tc.wantErr != "" {
				if err == nil || !strings.Contains(err.Error(), tc.wantErr) {
					t.Fatalf("got error %v, want one containing %q", err, tc.wantErr)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			for _, want := range tc.want {
				if !strings.Contains(string(src), want) {
					t.Errorf("source lacks %q:\n%s", want, src)
				}
			}
			// spec: SUPPORTED permissions are left out.
			if strings.Contains(string(src), "svc.things.verb") {
				t.Errorf("source lists SUPPORTED permissions:\n%s", src)
			}
		})
	}
}
