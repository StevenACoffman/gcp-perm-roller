// row is one table row as the support page writes it.
func row(perm, level string) string {
	return fmt.Sprintf(
		"<tr>\n      <td class=\"column1-class\"><code translate=\"no\" dir=\"ltr\">%s</code></td>\n"+
			"      <td class=\"column2-class\"><code translate=\"no\" dir=\"ltr\">%s</code></td>\n    </tr>\n",
		perm,
		level,
	)
}

// supportPage is a support page listing extra after enough SUPPORTED
// permissions to pass the size check: svc.things.verbN.
func supportPage(extra ...string) string {
	var b strings.Builder
	// The legend's rows have no column classes, so they are not permissions.
	b.WriteString(
		"<tr><td><code>NOT_SUPPORTED</code></td><td>The permission is not supported.</td></tr>\n",
	)
	for i := range minSupportRows {
		b.WriteString(row(fmt.Sprintf("svc.things.verb%d", i), "SUPPORTED"))
	}
	for _, r := range extra {
		b.WriteString(r)
	}
	return b.String()
}

// denyPage is a deny page listing the v2 names of svc.things.verbN, which
// follow from their v1 names, then extra v2 names.
func denyPage(extra ...string) string {
	var b strings.Builder
	// A permission group names no single permission.
	b.WriteString("<td><code>svc.googleapis.com/*.*</code></td>\n")
	for i := range minDenyNames {
		fmt.Fprintf(&b, "<td><code>svc.googleapis.com/things.verb%d</code></td>\n", i)
	}
	for _, name := range extra {
		fmt.Fprintf(&b, "<td><code translate=\"no\">%s</code></td>\n", name)
	}
	return b.String()
}

func TestGenerate(t *testing.T) {
	tests := map[string]struct {
		support, deny string
		status        int
		want          map[string][]string // lines each file must contain
		wantErr       string
	}{
		"exceptions only, sorted": {
			support: supportPage(
				row("b.things.list", "TESTING"),
				row("a.things.get", "NOT_SUPPORTED"),
				row("b.things.list", "TESTING"),
				row("resourcemanager.projects.delete", "SUPPORTED"),
				row("bigquery.connections.use", "SUPPORTED"),
				row("datastore.connections.use", "SUPPORTED"),
			),
			deny: denyPage(
				// spec: a v2 name the v1 name implies is not written.
				"a.googleapis.com/things.get",
				// spec: one v1 permission has the resource and verb.
				"cloudresourcemanager.googleapis.com/projects.delete",
				// spec: of two, the one whose service the label contains.
				"bigqueryconnection.googleapis.com/connections.use",
				// spec: a name no v1 permission has is left out.
				"nowhere.googleapis.com/ghosts.haunt",
			),
			status: http.StatusOK,
			want: map[string][]string{
				"support_levels.go": {
					"// Code generated by gensupport from " + supportURL + "; DO NOT EDIT.",
					"\t\"a.things.get\":  NotSupported,\n\t\"b.things.list\": Testing,\n}",
				},
				"deny_names.go": {
					"// Code generated by gensupport from " + denyURL + "; DO NOT EDIT.",
					"\t\"bigquery.connections.use\":        " +
						"\"bigqueryconnection.googleapis.com/connections.use\",\n" +
						"\t\"resourcemanager.projects.delete\": " +
						"\"cloudresourcemanager.googleapis.com/projects.delete\",\n}",
				},
			},
		},
		"too few rows": {
			support: row("a.things.get", "NOT_SUPPORTED"),
			deny:    denyPage(),
			status:  http.StatusOK,
			wantErr: "found 1 permissions, expected at least 10000",
		},
		"too few deny names": {
			support: supportPage(),
			deny:    "<td><code>svc.googleapis.com/things.verb0</code></td>",
			status:  http.StatusOK,
			wantErr: "found 1 permissions, expected at least 5000",
		},
		"unknown level": {
			support: supportPage(row("a.things.get", "MAYBE")),
			deny:    denyPage(),
			status:  http.StatusOK,
			wantErr: `a.things.get: unknown support level "MAYBE"`,
		},
		"conflicting levels": {
			support: supportPage(
				row("a.things.get", "TESTING"), row("a.things.get", "NOT_SUPPORTED"),
			),
			deny:    denyPage(),
			status:  http.StatusOK,
			wantErr: "a.things.get is listed as both TESTING and NOT_SUPPORTED",
		},
		"server error": {
			status:  http.StatusInternalServerError,
			wantErr: "500 Internal Server Error",
		},
	}
	for name, tc := range tests {
		t.Run(name, func(t *testing.T) {
			srv := httptest.NewServer(
				http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
					w.WriteHeader(tc.status)
					if r.URL.Path == "/deny" {
						fmt.Fprint(w, tc.deny)
					} else {
						fmt.Fprint(w, tc.support)
					}
				}),
			)
			t.Cleanup(srv.Close)

			files, err := generate(
				context.Background(), srv.Client(), srv.URL+"/support", srv.URL+"/deny",
			)
			if tc.wantErr != "" {
				if err == nil || !strings.Contains(err.Error(), tc.wantErr) {
					t.Fatalf("got error %v, want one containing %q", err, tc.wantErr)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			for file, lines := range tc.want {
				src := string(files[file])
				for _, want := range lines {
					if !strings.Contains(src, want) {
						t.Errorf("%s lacks %q:\n%s", file, want, src)
					}
				}
				// spec: entries that follow the default are left out.
				if strings.Contains(src, "svc.things.verb") ||
					strings.Contains(src, "a.things.get\": \"") {
					t.Errorf("%s lists entries that need no exception:\n%s", file, src)
				}
			}
			if len(files) != len(tc.want) {
				t.Errorf("wrote %d files, want %d", len(files), len(tc.want))
			}
		})
	}
}
