// annotation is the line, and the blank line after it, that tells mutago to
// skip the entries of the files gensupport writes.
const annotation = "// mutator-disable-regexp ^\\t\" *\n\n"

// row is one table row as the support page writes it.
func row(perm, level string) string {
	return fmt.Sprintf(
		"<tr>\n      <td class=\"column1-class\"><code translate=\"no\" dir=\"ltr\">%s</code></td>\n"+
			"      <td class=\"column2-class\"><code translate=\"no\" dir=\"ltr\">%s</code></td>\n    </tr>\n",
		perm,
		level,
	)
}

// supportPage is a support page listing extra after enough SUPPORTED
// permissions to pass the size check: svc.things.verbN.
func supportPage(extra ...string) string {
	var b strings.Builder
	// The legend's rows have no column classes, so they are not permissions.
	b.WriteString(
		"<tr><td><code>NOT_SUPPORTED</code></td><td>The permission is not supported.</td></tr>\n",
	)
	for i := range minSupportRows {
		b.WriteString(row(fmt.Sprintf("svc.things.verb%d", i), "SUPPORTED"))
	}
	for _, r := range extra {
		b.WriteString(r)
	}
	return b.String()
}

// denyPage is a deny page listing the v2 names of svc.things.verbN, which
// follow from their v1 names, then extra v2 names.
func denyPage(extra ...string) string {
	var b strings.Builder
	// A permission group names no single permission.
	b.WriteString("<td><code>svc.googleapis.com/*.*</code></td>\n")
	for i := range minDenyNames {
		fmt.Fprintf(&b, "<td><code>svc.googleapis.com/things.verb%d</code></td>\n", i)
	}
	for _, name := range extra {
		fmt.Fprintf(&b, "<td><code translate=\"no\">%s</code></td>\n", name)
	}
	return b.String()
}

func TestGenerate(t *testing.T) {
	tests := map[string]struct {
		support, deny string
		status        int
		// denyStatus, when set, is the deny page's status instead.
		denyStatus int
		// want is the whole of each file written: entries that follow the
		// default are left out, and mutago is told to skip the rest.
		want    map[string]string
		wantErr string
	}{
		"exceptions only, sorted": {
			support: supportPage(
				row("b.things.list", "TESTING"),
				row("a.things.get", "NOT_SUPPORTED"),
				row("b.things.list", "TESTING"),
				row("resourcemanager.projects.delete", "SUPPORTED"),
				row("bigquery.connections.use", "SUPPORTED"),
				row("datastore.connections.use", "SUPPORTED"),
				row("lookerstudio.pro.manage", "SUPPORTED"),
				row("bigtable.backups.restore", "SUPPORTED"),
				row("alpha.widgets.get", "SUPPORTED"),
				row("file.backups.update", "SUPPORTED"),
				row("netapp.backups.update", "SUPPORTED"),
			),
			deny: denyPage(
				// spec: a v2 name the v1 name implies is not written.
				"a.googleapis.com/things.get",
				// spec: the one v1 permission whose service the label
				// contains.
				"cloudresourcemanager.googleapis.com/projects.delete",
				// spec: of two, the one whose service the label contains.
				"bigqueryconnection.googleapis.com/connections.use",
				// spec: with none, the only v1 permission with the resource
				// and verb, as Looker Studio's.
				"datastudio.googleapis.com/pro.manage",
				// spec: a name no v1 permission has is left out.
				"nowhere.googleapis.com/ghosts.haunt",
				// spec: a v1 permission whose own v2 name is listed is not
				// given another service's, as Secret Manager's would be
				// before the support page lists it.
				"bigtable.googleapis.com/backups.restore",
				"secretmanager.googleapis.com/backups.restore",
				// spec: a v1 permission two v2 names match is left out.
				"beta.googleapis.com/widgets.get",
				"gamma.googleapis.com/widgets.get",
				// spec: of two, neither of which the label contains, neither.
				"secretmanager.googleapis.com/backups.update",
			),
			status: http.StatusOK,
			want: map[string]string{
				"support_levels.go": "// Code generated by gensupport from " + supportURL +
					"; DO NOT EDIT.\n\n" + annotation + `package gcpperms

// customRoleSupport is the support level in custom roles of each
// permission that is not SUPPORTED. CustomRoleSupport reads it.
var customRoleSupport = map[string]SupportLevel{
	"a.things.get":  NotSupported,
	"b.things.list": Testing,
}
`,
				"deny_names.go": "// Code generated by gensupport from " + denyURL +
					"; DO NOT EDIT.\n\n" + annotation + `package gcpperms

// denyNames is the v2 name of each permission whose v2 name is not its
// v1 name's service, ".googleapis.com/", and the rest. V2Name reads it.
var denyNames = map[string]string{
	"bigquery.connections.use":        "bigqueryconnection.googleapis.com/connections.use",
	"lookerstudio.pro.manage":         "datastudio.googleapis.com/pro.manage",
	"resourcemanager.projects.delete": "cloudresourcemanager.googleapis.com/projects.delete",
}
`,
			},
		},
		"exactly as many entries as required": {
			support: supportPage(),
			deny:    denyPage(),
			status:  http.StatusOK,
			want: map[string]string{
				"support_levels.go": "// Code generated by gensupport from " + supportURL +
					"; DO NOT EDIT.\n\n" + annotation + `package gcpperms

// customRoleSupport is the support level in custom roles of each
// permission that is not SUPPORTED. CustomRoleSupport reads it.
var customRoleSupport = map[string]SupportLevel{}
`,
				"deny_names.go": "// Code generated by gensupport from " + denyURL +
					"; DO NOT EDIT.\n\n" + annotation + `package gcpperms

// denyNames is the v2 name of each permission whose v2 name is not its
// v1 name's service, ".googleapis.com/", and the rest. V2Name reads it.
var denyNames = map[string]string{}
`,
			},
		},
		"too few rows": {
			support: row("a.things.get", "NOT_SUPPORTED"),
			deny:    denyPage(),
			status:  http.StatusOK,
			wantErr: "found 1 permissions, expected at least 10000",
		},
		"too few deny names": {
			support: supportPage(),
			deny:    "<td><code>svc.googleapis.com/things.verb0</code></td>",
			status:  http.StatusOK,
			wantErr: "found 1 permissions, expected at least 5000",
		},
		"unknown level": {
			support: supportPage(row("a.things.get", "MAYBE")),
			deny:    denyPage(),
			status:  http.StatusOK,
			wantErr: `a.things.get: unknown support level "MAYBE"`,
		},
		"conflicting levels": {
			support: supportPage(
				row("a.things.get", "TESTING"), row("a.things.get", "NOT_SUPPORTED"),
			),
			deny:    denyPage(),
			status:  http.StatusOK,
			wantErr: "a.things.get is listed as both TESTING and NOT_SUPPORTED",
		},
		"server error": {
			status:  http.StatusInternalServerError,
			wantErr: "500 Internal Server Error",
		},
		"deny page server error": {
			support:    supportPage(),
			status:     http.StatusOK,
			denyStatus: http.StatusNotFound,
			wantErr:    "/deny: 404 Not Found",
		},
	}
	for name, tc := range tests {
		t.Run(name, func(t *testing.T) {
			srv := httptest.NewServer(
				http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
					if r.URL.Path == "/deny" {
						w.WriteHeader(cmp.Or(tc.denyStatus, tc.status))
						fmt.Fprint(w, tc.deny)
					} else {
						w.WriteHeader(tc.status)
						fmt.Fprint(w, tc.support)
					}
				}),
			)
			t.Cleanup(srv.Close)

			files, err := generate(
				context.Background(), srv.Client(), srv.URL+"/support", srv.URL+"/deny",
			)
			if tc.wantErr != "" {
				if err == nil || !strings.Contains(err.Error(), tc.wantErr) {
					t.Fatalf("got error %v, want one containing %q", err, tc.wantErr)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			for file, want := range tc.want {
				if got := string(files[file]); got != want {
					t.Errorf("%s is\n%s\nwant\n%s", file, got, want)
				}
			}
			if len(files) != len(tc.want) {
				t.Errorf("wrote %d files, want %d", len(files), len(tc.want))
			}
		})
	}
}

func TestGenerateUnreachable(t *testing.T) {
	srv := httptest.NewServer(http.NotFoundHandler())
	closed := srv.URL
	srv.Close()
	tests := map[string]struct {
		url, want string
	}{
		// spec: a URL no request can be made for, and a server that does not
		// answer, both name the URL.
		"bad URL":   {url: "http://bad host/", want: "fetching http://bad host/"},
		"no answer": {url: closed, want: "fetching " + closed},
	}
	for name, tc := range tests {
		t.Run(name, func(t *testing.T) {
			_, err := generate(context.Background(), http.DefaultClient, tc.url, tc.url)
			if err == nil || !strings.HasPrefix(err.Error(), tc.want) {
				t.Fatalf("got error %v, want one starting %q", err, tc.want)
			}
		})
	}
}
