// Command gensupport writes support_levels.go in the current directory: the
// permissions that Google's list of support levels for permissions in custom
// roles marks TESTING or NOT_SUPPORTED. `go generate` runs it in
// internal/gcpperms.
//
// Only the exceptions are written, so a permission that is missing is
// SUPPORTED. The file carries no date, so regenerating it changes it only
// when a support level changes.
package main

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"go/format"
	"html"
	"io"
	"maps"
	"net/http"
	"os"
	"os/signal"
	"regexp"
	"slices"
	"strings"
)

// pageURL is Google's list of every permission and its support level.
const pageURL = "https://docs.cloud.google.com/iam/docs/custom-roles-permissions-support"

// minRows is fewer rows than the page has ever had (14,279 in October
// 2026). A page parsing to fewer has changed its layout, and writing what
// parsed would mark every permission it lost as SUPPORTED.
const minRows = 10000

// rowRE matches one row of the page's table: a permission and its level.
var rowRE = regexp.MustCompile(
	`<td class="column1-class">\s*<code[^>]*>([^<]+)</code>\s*</td>\s*` +
		`<td class="column2-class">\s*<code[^>]*>([^<]+)</code>\s*</td>`,
)

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt)
	src, err := generate(ctx, http.DefaultClient, pageURL)
	stop()
	if err == nil {
		err = os.WriteFile("support_levels.go", src, 0o644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "gensupport:", err)
		os.Exit(1)
	}
}

// generate fetches the page at url and returns the source of
// support_levels.go for it.
func generate(ctx context.Context, client *http.Client, url string) ([]byte, error) {
	page, err := fetch(ctx, client, url)
	if err != nil {
		return nil, err
	}
	levels, err := parseLevels(page)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", url, err)
	}
	return render(levels)
}

// fetch returns the body of the page at url.
func fetch(ctx context.Context, client *http.Client, url string) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, http.NoBody)
	if err != nil {
		return nil, fmt.Errorf("fetching %s: %w", url, err)
	}
	resp, err := client.Do(req)
	if err != nil {
		return nil, fmt.Errorf("fetching %s: %w", url, err)
	}
	body, readErr := io.ReadAll(resp.Body)
	if err := errors.Join(readErr, resp.Body.Close()); err != nil {
		return nil, fmt.Errorf("reading %s: %w", url, err)
	}
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("fetching %s: %s", url, resp.Status)
	}
	return body, nil
}

// parseLevels returns the level of every permission the page lists that
// is not SUPPORTED. It fails when the page lists fewer than minRows
// permissions, a permission twice with different levels, or a level it
// does not know.
func parseLevels(page []byte) (map[string]string, error) {
	rows := rowRE.FindAllSubmatch(page, -1)
	if len(rows) < minRows {
		return nil, fmt.Errorf("found %d permissions, expected at least %d", len(rows), minRows)
	}
	seen := make(map[string]string, len(rows))
	levels := make(map[string]string)
	for _, row := range rows {
		perm := strings.TrimSpace(html.UnescapeString(string(row[1])))
		level := strings.TrimSpace(html.UnescapeString(string(row[2])))
		if levelConst(level) == "" {
			return nil, fmt.Errorf("%s: unknown support level %q", perm, level)
		}
		if prev, ok := seen[perm]; ok && prev != level {
			return nil, fmt.Errorf("%s is listed as both %s and %s", perm, prev, level)
		}
		seen[perm] = level
		if level != "SUPPORTED" {
			levels[perm] = level
		}
	}
	return levels, nil
}

// render returns gofmt'd source declaring levels as customRoleSupport,
// sorted by permission.
func render(levels map[string]string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gensupport from %s; DO NOT EDIT.\n\n", pageURL)
	b.WriteString("package gcpperms\n\n")
	b.WriteString("// customRoleSupport is the support level in custom roles of each\n")
	b.WriteString("// permission that is not SUPPORTED. CustomRoleSupport reads it.\n")
	b.WriteString("var customRoleSupport = map[string]SupportLevel{\n")
	for _, perm := range slices.Sorted(maps.Keys(levels)) {
		fmt.Fprintf(&b, "\t%q: %s,\n", perm, levelConst(levels[perm]))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting the generated source: %w", err)
	}
	return src, nil
}

// levelConst names the gcpperms constant for a level the page uses, or
// returns "" for a level it does not know.
func levelConst(level string) string {
	switch level {
	case "SUPPORTED":
		return "Supported"
	case "TESTING":
		return "Testing"
	case "NOT_SUPPORTED":
		return "NotSupported"
	}
	return ""
}
