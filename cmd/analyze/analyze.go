// Package analyze implements the "analyze" command: it lists the Google
// Cloud API calls each program in a Go workspace can make, the IAM
// permissions they require, and the predefined roles that grant them.
package analyze

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/peterbourgon/ff/v4"

	"github.com/StevenACoffman/gcp-perm-roller/cmd/root"
	"github.com/StevenACoffman/gcp-perm-roller/internal/gcpperms"
	"github.com/StevenACoffman/gcp-perm-roller/internal/workspace"
)

const (
	// generatedPrefix starts every file --outdir writes, except JSON ones,
	// marking it as one a later run may replace or remove.
	generatedPrefix = "# Code generated by gcp-perm-roller"
	// legacyPrefix starts files that this tool generated when it was named
	// gcpperms, which a run also replaces or removes.
	legacyPrefix = "# Code generated by gcpperms"
)

// longHelp is the analyze command's help text.
const longHelp = `Analyze builds a whole-program call graph from each main package, finds
the Google Cloud SDK calls it can reach, and maps them to IAM permissions.

With no packages, every module of the workspace (or the current module) in
--dir is analyzed. Package patterns are resolved in --dir.

  gcp-perm-roller analyze -C ~/src/myworkspace
  gcp-perm-roller analyze -C ~/src/myworkspace ./cmd/server
  gcp-perm-roller analyze -C ~/src/myworkspace --format=predefined ./cmd/server
  gcp-perm-roller analyze -C ~/src/myworkspace --format=role ./cmd/server > role.yaml

To combine binaries from several workspaces, save each workspace's results
as JSON and read them back with --from:

  gcp-perm-roller analyze -C ~/src/one --format=json > one.json
  gcp-perm-roller analyze -C ~/src/two --format=json ./cmd/... > two.json
  gcp-perm-roller analyze --from=one.json --from=two.json --union --format=predefined`

// Config holds the configuration for the analyze command.
type Config struct {
	*root.Config
	Dir             string
	Format          string
	Roles           string
	RoleStages      []string
	WithConditional bool
	OutDir          string
	Union           bool
	Verbose         bool
	Strict          bool
	Tags            []string
	Jobs            int
	Algo            string
	Wrappers        []string
	From            []string
	Flags           *ff.FlagSet
	Command         *ff.Command
}

// New creates and registers the analyze command with the given parent config.
func New(parent *root.Config) *Config {
	var cfg Config
	cfg.Config = parent
	cfg.Flags = ff.NewFlagSet("analyze").SetParent(parent.Flags)
	cfg.bindFlags()
	cfg.Command = &ff.Command{
		Name:      "analyze",
		Usage:     "gcp-perm-roller analyze [FLAGS] [PACKAGES...]",
		ShortHelp: "list the GCP permissions and roles each binary in a workspace needs",
		LongHelp:  longHelp,
		Flags:     cfg.Flags,
		Exec:      cfg.exec,
	}
	parent.Command.Subcommands = append(parent.Command.Subcommands, cfg.Command)
	return &cfg
}

// bindFlags registers the command's flags on cfg.Flags.
func (cfg *Config) bindFlags() {
	cfg.Flags.StringVar(&cfg.Dir, 'C', "dir", ".",
		"run as if started in this directory: the workspace or module to analyze")
	cfg.Flags.StringEnumVar(&cfg.Format, 0, "format",
		"output format: text, json, role (gcloud custom role YAML), or "+
			"predefined (least-privilege predefined roles)",
		"text", "json", "role", "predefined")
	cfg.Flags.StringVar(&cfg.Roles, 0, "roles", "",
		"where to read predefined roles for --format=predefined or json: api (the IAM API, "+
			"using Application Default Credentials) or a path to saved roles, such as "+
			"iam-dataset's gcp/roles directory (default api for --format=predefined)")
	cfg.Flags.StringListVar(&cfg.RoleStages, 0, "role-stages",
		"launch stage of predefined roles to recommend; repeatable (default GA)")
	cfg.Flags.BoolVar(&cfg.WithConditional, 0, "include-conditional",
		"also cover conditional permissions when choosing predefined roles")
	cfg.Flags.StringVar(&cfg.OutDir, 0, "outdir", "",
		"write each binary's report to its own file in this directory, named for the "+
			"package's directory, instead of to stdout; binaries needing no permissions get no file")
	cfg.Flags.BoolVar(&cfg.Union, 0, "union", "merge all binaries into one report")
	cfg.Flags.BoolVar(&cfg.Verbose, 'v', "verbose",
		"show the call sites of each SDK call (text format)")
	cfg.Flags.BoolVar(&cfg.Strict, 0, "strict",
		"exit non-zero if any SDK call has no permission rule")
	cfg.Flags.StringListVar(&cfg.Tags, 0, "tags", "build tag; repeatable")
	cfg.Flags.IntVar(&cfg.Jobs, 'j', "jobs", 0,
		"binaries to analyze in parallel (0 = GOMAXPROCS, at most 4)")
	cfg.Flags.StringEnumVar(&cfg.Algo, 0, "algo",
		"call graph algorithm: vta (precise) or rta (faster, also reports methods only "+
			"reflection could call)", string(gcpperms.VTA), string(gcpperms.RTA))
	cfg.Flags.StringListVar(&cfg.Wrappers, 0, "wrapper",
		"function, as importpath.Func, that calls the functions passed to it by reflection, "+
			"such as a memoizing cache; calls to it count as calling them under vta; repeatable")
	cfg.Flags.StringListVar(&cfg.From, 0, "from",
		"read results saved with --format=json from this file instead of analyzing; "+
			"repeatable, to combine workspaces (with --union, into one report)")
}

func (cfg *Config) exec(ctx context.Context, args []string) error {
	var (
		res gcpperms.Result
		err error
	)
	if len(cfg.From) > 0 {
		if len(args) > 0 {
			return &root.UsageError{Err: errors.New(
				"analyze: --from reads saved results, so it takes no packages")}
		}
		res, err = loadResults(cfg.From)
	} else {
		res, err = cfg.analyze(ctx, args)
	}
	if err != nil {
		return err
	}
	if cfg.Union {
		res.Binaries = []gcpperms.Binary{res.Union("all binaries")}
	}
	if err := cfg.selectRoles(ctx, res.Binaries); err != nil {
		return fmt.Errorf("analyze: %w", err)
	}
	if cfg.OutDir != "" {
		err = cfg.writeFiles(ctx, res)
	} else {
		err = write(cfg.Stdout, cfg.Format, res, cfg.Verbose)
	}
	if err != nil {
		return fmt.Errorf("analyze: %w", err)
	}
	if n := unmapped(res.Binaries); cfg.Strict && n > 0 {
		return fmt.Errorf("analyze: %d SDK calls have no permission rule", n)
	}
	return nil
}

// analyze analyzes the binaries the patterns name, or every module of the
// workspace in cfg.Dir when there are none.
func (cfg *Config) analyze(ctx context.Context, patterns []string) (gcpperms.Result, error) {
	algorithm, err := gcpperms.ParseAlgorithm(cfg.Algo)
	if err != nil {
		return gcpperms.Result{}, &root.UsageError{Err: fmt.Errorf("analyze: %w", err)}
	}
	if len(patterns) == 0 {
		if patterns, err = workspace.Patterns(ctx, cfg.Dir, cfg.Stderr); err != nil {
			return gcpperms.Result{}, fmt.Errorf("analyze: %w", err)
		}
	}
	res, err := gcpperms.Analyze(&gcpperms.Config{
		Dir:         cfg.Dir,
		Patterns:    patterns,
		Algorithm:   algorithm,
		Parallelism: cfg.Jobs,
		Tags:        cfg.Tags,
		Wrappers:    cfg.Wrappers,
	})
	if err != nil {
		return gcpperms.Result{}, fmt.Errorf("analyze: %w", err)
	}
	for _, p := range res.Skipped {
		_, _ = fmt.Fprintf(cfg.Stderr,
			"warning: skipped %s: it or a dependency has type errors\n", p)
	}
	if len(res.Binaries)+len(res.Skipped) == 0 {
		// An empty report would look like binaries needing nothing.
		return gcpperms.Result{}, fmt.Errorf("analyze: no main packages match %s in %s",
			strings.Join(patterns, " "), cfg.Dir)
	}
	return res, nil
}

// loadResults reads and concatenates results saved with --format=json.
func loadResults(files []string) (gcpperms.Result, error) {
	var all gcpperms.Result
	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			return gcpperms.Result{}, fmt.Errorf("analyze: %w", err)
		}
		var res gcpperms.Result
		if err := json.Unmarshal(data, &res); err != nil {
			return gcpperms.Result{}, fmt.Errorf("analyze: parsing %s: %w", file, err)
		}
		all.Binaries = append(all.Binaries, res.Binaries...)
		all.Skipped = append(all.Skipped, res.Skipped...)
		all.Errors = append(all.Errors, res.Errors...)
	}
	return all, nil
}

// selectRoles chooses each binary's predefined roles when --roles is given
// or the format needs them.
func (cfg *Config) selectRoles(ctx context.Context, bins []gcpperms.Binary) error {
	from := cfg.Roles
	if from == "" && cfg.Format == "predefined" {
		from = "api"
	}
	if from == "" {
		return nil
	}
	roles, err := loadRoles(ctx, from)
	if err != nil {
		return err
	}
	stages := cfg.RoleStages
	if len(stages) == 0 {
		stages = []string{"GA"}
	}
	filter := gcpperms.RoleFilter{Stages: stages}
	for i := range bins {
		need := bins[i].Permissions()
		if cfg.WithConditional {
			need = append(need, bins[i].ConditionalPermissions()...)
		}
		sel := gcpperms.SelectRoles(need, roles, filter)
		bins[i].PredefinedRoles = &sel
	}
	return nil
}

// unmapped counts the SDK calls with no permission rule.
func unmapped(bins []gcpperms.Binary) int {
	n := 0
	for _, b := range bins {
		n += len(b.Unmapped())
	}
	return n
}

// commandLine is the command that reproduces the report's content, for the
// header of generated files. It leaves out --dir and --outdir, which say
// where the report was made and written rather than what it holds.
func (cfg *Config) commandLine() string {
	words := []string{"gcp-perm-roller", "analyze", "--format=" + cfg.Format}
	if cfg.Roles != "" {
		words = append(words, "--roles="+cfg.Roles)
	}
	for _, s := range cfg.RoleStages {
		words = append(words, "--role-stages="+s)
	}
	if cfg.WithConditional {
		words = append(words, "--include-conditional")
	}
	if cfg.Union {
		words = append(words, "--union")
	}
	if cfg.Verbose {
		words = append(words, "--verbose")
	}
	for _, t := range cfg.Tags {
		words = append(words, "--tags="+t)
	}
	if cfg.Algo != string(gcpperms.VTA) {
		words = append(words, "--algo="+cfg.Algo)
	}
	for _, w := range cfg.Wrappers {
		words = append(words, "--wrapper="+w)
	}
	return strings.Join(words, " ")
}

// write writes res in format.
func write(w io.Writer, format string, res gcpperms.Result, verbose bool) error {
	var err error
	switch format {
	case "text":
		err = gcpperms.WriteText(w, res.Binaries, verbose)
	case "json":
		err = gcpperms.WriteJSON(w, res)
	case "role":
		err = gcpperms.WriteRoles(w, res.Binaries)
	case "predefined":
		err = gcpperms.WritePredefinedRoles(w, res.Binaries)
	default:
		return fmt.Errorf("unknown format %q", format)
	}
	if err != nil {
		return fmt.Errorf("writing the %s report: %w", format, err)
	}
	return nil
}

// extension is the file extension --outdir uses for format.
func extension(format string) string {
	switch format {
	case "json":
		return ".json"
	case "role":
		return ".yaml"
	default:
		return ".txt"
	}
}

// writeFiles writes each binary that needs permissions to its own file in
// cfg.OutDir, named for its package directory relative to cfg.Dir with
// slashes turned into dashes: billing/cmd/worker becomes
// billing-cmd-worker. Generated files from earlier runs that this run does
// not rewrite are removed, so binaries that went away leave nothing behind.
func (cfg *Config) writeFiles(ctx context.Context, res gcpperms.Result) error {
	mods, err := workspace.Modules(ctx, cfg.Dir, cfg.Stderr)
	if err != nil {
		return fmt.Errorf("finding the modules: %w", err)
	}
	base, err := filepath.Abs(cfg.Dir)
	if err != nil {
		return fmt.Errorf("resolving %s: %w", cfg.Dir, err)
	}
	if err := os.MkdirAll(cfg.OutDir, 0o750); err != nil {
		return fmt.Errorf("creating the output directory: %w", err)
	}
	header := fmt.Sprintf("# Code generated by %s; DO NOT EDIT.\n", cfg.commandLine())
	written := make(map[string]bool)
	for _, b := range res.Binaries {
		if len(b.Permissions())+len(b.ConditionalPermissions()) == 0 {
			continue
		}
		name := strings.ReplaceAll(packageDir(b.Package, mods, base), "/", "-") +
			extension(cfg.Format)
		var buf bytes.Buffer
		if cfg.Format != "json" {
			buf.WriteString(header)
		}
		one := gcpperms.Result{Binaries: []gcpperms.Binary{b}}
		if err := write(&buf, cfg.Format, one, cfg.Verbose); err != nil {
			return err
		}
		file := filepath.Join(cfg.OutDir, name)
		if err := os.WriteFile(file, buf.Bytes(), 0o600); err != nil {
			return fmt.Errorf("writing %s: %w", file, err)
		}
		written[name] = true
	}
	return removeStale(cfg.OutDir, written)
}

// removeStale removes generated files in dir that are not in keep.
func removeStale(dir string, keep map[string]bool) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("listing %s: %w", dir, err)
	}
	for _, e := range entries {
		if e.IsDir() || keep[e.Name()] {
			continue
		}
		file := filepath.Join(dir, e.Name())
		data, err := os.ReadFile(file)
		if err != nil {
			return fmt.Errorf("reading %s: %w", file, err)
		}
		if !generated(data) {
			continue
		}
		if err := os.Remove(file); err != nil {
			return fmt.Errorf("removing %s: %w", file, err)
		}
	}
	return nil
}

// generated reports whether data is a file --outdir wrote.
func generated(data []byte) bool {
	return bytes.HasPrefix(data, []byte(generatedPrefix)) ||
		bytes.HasPrefix(data, []byte(legacyPrefix))
}

// packageDir is the directory of the package with import path pkg,
// relative to base, found through the module containing it. Packages
// outside every module keep their import path.
func packageDir(pkg string, mods map[string]string, base string) string {
	best := ""
	for m := range mods {
		if (pkg == m || strings.HasPrefix(pkg, m+"/")) && len(m) > len(best) {
			best = m
		}
	}
	if best == "" {
		return pkg
	}
	dir := filepath.Join(mods[best], strings.TrimPrefix(pkg, best))
	rel, err := filepath.Rel(base, dir)
	if err != nil || rel == "." || strings.HasPrefix(rel, "..") {
		return pkg
	}
	return filepath.ToSlash(rel)
}

// loadRoles reads predefined roles from the IAM API, or from a saved copy.
func loadRoles(ctx context.Context, from string) ([]gcpperms.Role, error) {
	var (
		roles []gcpperms.Role
		err   error
	)
	if from == "api" {
		roles, err = gcpperms.LoadRolesFromAPI(ctx)
	} else {
		roles, err = gcpperms.LoadRolesFromPath(from)
	}
	if err != nil {
		return nil, fmt.Errorf("loading predefined roles: %w", err)
	}
	return roles, nil
}
